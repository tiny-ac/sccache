#!/usr/bin/env bash
# Regenerates src/reapi/proto/*.rs, except mod.rs, from the Remote Execution API's
# protobuf files, downloaded at the commits below. Needs curl and cargo.
set -euo pipefail

# Fixed commits, so every run generates the same code and CI can diff it. To update
# the protos, change a commit and rerun this script.
REMOTE_APIS_COMMIT=6def1c5d27a527c400875c24ae8b1a160145d7e1
GOOGLEAPIS_COMMIT=886464f687986b8b38392d83957a5a2ead4dcf71

script_dir=$(cd "$(dirname "$0")" && pwd)
proto_module_dir=$script_dir/../../src/reapi/proto
temp_dir=$(mktemp -d)
trap 'rm -rf "$temp_dir"' EXIT

fetch() {
    local repo_at_commit=$1 path=$2
    mkdir -p "$temp_dir/$(dirname "$path")"
    curl -fsSL "https://raw.githubusercontent.com/$repo_at_commit/$path" -o "$temp_dir/$path"
}
for proto in build/bazel/remote/execution/v2/remote_execution.proto build/bazel/semver/semver.proto; do
    fetch "bazelbuild/remote-apis/$REMOTE_APIS_COMMIT" "$proto"
done
for proto in google/api/annotations.proto google/api/client.proto google/api/field_behavior.proto \
    google/api/http.proto google/api/launch_stage.proto google/bytestream/bytestream.proto \
    google/longrunning/operations.proto google/rpc/error_details.proto google/rpc/status.proto; do
    fetch "googleapis/googleapis/$GOOGLEAPIS_COMMIT" "$proto"
done

mkdir -p "$temp_dir/gen"
cargo run --quiet --locked --manifest-path "$script_dir/Cargo.toml" --target-dir "$temp_dir/target" -- \
    "$temp_dir" "$temp_dir/gen"

# Drop files of packages no longer generated.
mkdir -p "$proto_module_dir"
find "$proto_module_dir" -name '*.rs' ! -name mod.rs -delete
# Names the source of a generated file and copies each proto's copyright and license notice.
header() {
    local repo=$1 commit=$2 proto
    shift 2
    echo "// Generated by scripts/reapi-protogen from $repo at commit $commit."
    for proto in "$@"; do
        echo "//"
        echo "// From $proto:"
        echo "//"
        sed -n '/^\/\//!q;p' "$temp_dir/$proto"
    done
    echo
}
generate() {
    local package=$1 repo=$2 commit=$3
    shift 3
    { header "$repo" "$commit" "$@"; cat "$temp_dir/gen/$package.rs"; } > "$proto_module_dir/$package.rs"
}
remote_apis=(bazelbuild/remote-apis "$REMOTE_APIS_COMMIT")
googleapis=(googleapis/googleapis "$GOOGLEAPIS_COMMIT")
generate build.bazel.remote.execution.v2 "${remote_apis[@]}" build/bazel/remote/execution/v2/remote_execution.proto
generate build.bazel.semver "${remote_apis[@]}" build/bazel/semver/semver.proto
# Skips google.api, which holds only annotations the generated code doesn't reference.
generate google.bytestream "${googleapis[@]}" google/bytestream/bytestream.proto
generate google.longrunning "${googleapis[@]}" google/longrunning/operations.proto
generate google.rpc "${googleapis[@]}" google/rpc/error_details.proto google/rpc/status.proto
